"""Generates tests/fixtures/large/: a FICTIONAL large project (about 150 parts, 450+ wires) for the export-job tests and measurements.
Deterministic (no randomness, no dates): run it again and the files do not change. Usage: python tools/make_large_fixture.py [out dir] [--light]
The full project returns every sensor's ground straight to the one ground bus (151 wires on it: the stress case for the drawing engine). `--light` returns
the grounds through one splice per controller instead (7 wires on the bus): the same parts and wires, a project the engine draws in seconds."""
from __future__ import annotations

import sys
from pathlib import Path

CONTROLLERS, SENSORS = 6, 24  # per controller 3 wires per sensor and a supply; the ground bus gets a wire per sensor and controller

YML = """# Large fictional project for the export-job tests (generated by tools/make_large_fixture.py; do not edit by hand).
wirelist: wirelist
cards: cards
out: out

buses: [GNDB, BB1]
breaker_prefixes: [CB-]
splice_prefix: SP-
"""
CARD = """# Interface card: fictional auxiliary battery whose terminals are written with pin numbers and no connector name

```yaml schemagen
device: '^BATX$'
part: fictional 3-pin auxiliary battery
kind: battery
source: {v_oc: 12.6, r_int: 0.05, provenance: design}
```
"""


def wirelist(light: bool = False) -> str:
    rows: list[str] = []
    ctrl = lambda k: f"EC{k} controller {k}"  # noqa: E731
    sns = lambda k, n: f"S{k}{n:02d} sensor {k}.{n}"  # noqa: E731

    def row(i: str, p1: str, p1c: str, p1p: str, p2: str, p2c: str, p2p: str, func: str, bus: str, awg: str = "22") -> None:
        rows.append(f'row("{i}", "{p1}", "{p1c}", "{p1p}", "{p2}", "{p2c}", "{p2p}", "{func}", "{bus}", "{awg}")')

    row("PWR-BUS-1", "BAT battery 14 V", "+", "", "BB1 14 V bus bar", "Stud", "", "Bus feed", "14 V", "8")
    row("GND-BAT-1", "BAT battery 14 V", "−", "", "GNDB ground bus", "Stud", "", "Battery return", "GND", "8")
    sp = 0
    for k in range(1, CONTROLLERS + 1):
        row(f"PWR-CB{k}-A", "BB1 14 V bus bar", "Stud", "", f"CB-C{k} 5 A", "LINE", "", f"Controller {k} breaker feed", "14 V", "20")
        row(f"PWR-CB{k}-B", f"CB-C{k} 5 A", "LOAD", "", ctrl(k), "J1", "1", f"Controller {k} supply", "14 V", "20")
        row(f"GND-EC{k}", ctrl(k), "J1", "2", "GNDB ground bus", "Stud", "", f"Controller {k} ground", "GND", "20")
        for n in range(1, SENSORS + 1):
            a, b = 3 + 2 * (n - 1), 4 + 2 * (n - 1)
            row(f"SIG-{k}{n:02d}-A", ctrl(k), "J1", str(a), sns(k, n), "P1", "1", f"Signal {k}.{n} A", "—")
            row(f"SIG-{k}{n:02d}-B", ctrl(k), "J1", str(b), sns(k, n), "P1", "3", f"Signal {k}.{n} B", "—")
            end = (f"SP-G{k} ground splice {k}", "Splice") if light else ("GNDB ground bus", "Stud")
            row(f"GND-S{k}{n:02d}", sns(k, n), "P1", "2", *end, "", f"Sensor {k}.{n} ground", "GND")
        if light: row(f"GND-SPG{k}", f"SP-G{k} ground splice {k}", "Splice", "", "GNDB ground bus", "Stud", "", f"Ground splice {k} to the bus", "GND", "14")
        for n in (1, 7, 13, 19):  # a shared supply: one splice feeds two sensors
            sp += 1
            s = f"SP-{sp:02d} power splice {sp}"
            row(f"PWR-SP{sp:02d}-A", "BB1 14 V bus bar", "Stud", "", s, "Splice", "", f"Splice {sp} feed", "14 V", "20")
            row(f"PWR-SP{sp:02d}-B", s, "Splice", "", sns(k, n), "P1", "4", f"Splice {sp} to sensor {k}.{n}", "14 V")
            row(f"PWR-SP{sp:02d}-C", s, "Splice", "", sns(k, n + 1), "P1", "4", f"Splice {sp} to sensor {k}.{n + 1}", "14 V")
    # jumpers inside one connector and a three-terminal battery written with pin numbers only
    row("JMP-1", "JMP jumper unit", "J1", "1", "JMP jumper unit", "J1", "3", "Jumper 1", "—", "22 AWG")
    row("JMP-2", "JMP jumper unit", "J1", "2", "JMP jumper unit", "J1", "4", "Jumper 2", "—", "22 AWG")
    row("BX-1", "BATX battery aux", "", "1", "JMP jumper unit", "J1", "7", "Aux plus", "14 V", "22 AWG")
    row("BX-2", "BATX battery aux", "", "2", "JMP jumper unit", "J1", "8", "Aux minus", "GND", "22 AWG")
    row("BX-3", "BATX battery aux", "", "3", "JMP jumper unit", "J1", "9", "Aux status", "—", "22 AWG")
    brk = ",\n     ".join(f'dict(id="CB-C{k}", rating=5, panel="C{k}", loads=["EC{k}"])' for k in range(1, CONTROLLERS + 1))
    head = '"""Large fictional fixture wire list (generated by tools/make_large_fixture.py)."""\nSUBSYSTEM = ("SS-01", "Large")\nR = []\n\n\n'
    head += ("def row(id, p1, p1c, p1p, p2, p2c, p2p, func, bus, awg, st=\"Proposed\", name=\"\"):\n"
             "    R.append(dict(id=id, name=name, p1=p1, p1c=p1c, p1p=p1p, p2=p2, p2c=p2c, p2p=p2p, func=func, bus=bus, awg=awg, st=st))\n\n\n")
    return head + "\n".join(rows) + f"\n\nP = [{brk}]\nD = []\nO = []\n"


def main(out: Path, light: bool = False) -> None:
    (out / "wirelist").mkdir(parents=True, exist_ok=True); (out / "cards").mkdir(exist_ok=True)
    for name, text in (("schemagen.yml", YML), ("cards/BATX_card.md", CARD), ("wirelist/ss01_large.py", wirelist(light))):
        (out / name).write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    a = [x for x in sys.argv[1:] if x != "--light"]
    main(Path(a[0]) if a else Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "large", "--light" in sys.argv)
